export function illustrationKey(scene) {
 const {kind,actor,action,prop,color,size,reference,position} = scene;
 if(kind==='give') return `give:${scene.giver}:${scene.receiver}:${prop}`;
 if(kind==='color' && prop==='hat') return `${actor}:hat:${color}`;
 if(kind==='color' && action==='read') return `${actor}:read:${color}`;
 if(kind==='size' && prop==='apple') return `${actor}:apple:${size}`;
 if(kind==='size' && prop==='box') return `${actor}:box:size:${size}`;
 if(kind==='color' && action==='water' && prop==='flower') return `${actor}:water:${color}`;
 if(kind==='color' && action==='ball') return `${actor}:ball:color:${color}`;
 if(kind==='size' && prop==='ball') return `${actor}:ball:size:${size}`;
 if(kind==='position') return `${actor}:${reference}:${position}`;
 if(kind==='action' && !prop) return `${actor}:${action}`;
 return null;
}
export function illustratedScene(scene,{x=0,y=0,width=320,height=240}={}) {
 const key=illustrationKey(scene),frame=ILLUSTRATION_FRAMES[key];
 if(!frame)return '';
 const sheet=ILLUSTRATION_ATLASES[frame.atlas],[x0,x1]=sheet.xRanges[frame.column],[y0,y1]=sheet.yRanges[frame.row];
 const left=x0+2,top=y0+2,w=x1-x0-4,h=y1-y0-4,id='illustration-'+key.replaceAll(':','-');
 const action=scene.action,actor=scene.actor,human=['mom','dad','yeonwoo'].includes(actor);
 return `<svg data-illustrated-scene="${key}" ${action?`data-action-pose="${actor}:${action}"`:''} ${action==='sleep'?(human?'data-human-bed="true"':`data-sleep-pose="${actor}"`):''} x="${x}" y="${y}" width="${width}" height="${height}" viewBox="${left} ${top} ${w} ${h}" overflow="hidden" preserveAspectRatio="xMidYMid meet"><defs><clipPath id="${id}" clipPathUnits="userSpaceOnUse"><rect x="${left}" y="${top}" width="${w}" height="${h}"/></clipPath></defs><image clip-path="url(#${id})" href="${sheet.file}" width="${sheet.width}" height="${sheet.height}"/></svg>`;
}
